using UnityEngine;

namespace Sailboat.Simulation
{
    /// <summary>
    /// Forces and torques acting on the sailboat at a single moment.
    /// Used by the simulation step and for debug drawing.
    /// </summary>
    public readonly struct SailboatForces
    {
        public SailboatForces(Vector2 apparentWind, Vector2 sailForce, Vector2 hullForce, float rudderTorque, float dampingTorque)
        {
            ApparentWind = apparentWind;
            SailForce = sailForce;
            HullForce = hullForce;
            RudderTorque = rudderTorque;
            DampingTorque = dampingTorque;
        }

        /// <summary>
        /// Wind felt on board (true wind minus boat velocity), in m/s.
        /// </summary>
        public Vector2 ApparentWind { get; }

        /// <summary>
        /// Force generated by the sail, in newtons.
        /// </summary>
        public Vector2 SailForce { get; }

        /// <summary>
        /// Water resistance of the hull and keel, in newtons. Always opposes the motion.
        /// </summary>
        public Vector2 HullForce { get; }

        /// <summary>
        /// Torque generated by the rudder in N*m. Positive turns the bow to starboard.
        /// </summary>
        public float RudderTorque { get; }

        /// <summary>
        /// Torque resisting the rotation in N*m. Always opposes the angular velocity.
        /// </summary>
        public float DampingTorque { get; }
    }
}                                           
                                            